"""Internal model output; these fields are not part of the public API."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, StrictBool, model_validator

from app.schemas.create_event import CreateEventAction, CreateEventDraft
from app.schemas.delete_event import DeleteFindCandidatesAction, DeleteSearchDraft
from app.schemas.list_events import ListEventsAction, ListEventsDraft
from app.schemas.search_events import SearchEventsAction, SearchEventsDraft
from app.schemas.update_event import UpdateFindCandidatesAction, UpdateSearchDraft


class DeleteSelectionAction(BaseModel):
    """Internal selection: the service maps shown numbers to stored IDs."""

    model_config = ConfigDict(extra="forbid")
    phase: Literal["delete_confirmed"]
    selected_numbers: list[int] = Field(min_length=1)

    @model_validator(mode="after")
    def unique_numbers(self):
        if any(number < 1 for number in self.selected_numbers):
            raise ValueError("selected_numbers must be positive")
        if len(self.selected_numbers) != len(set(self.selected_numbers)):
            raise ValueError("selected_numbers must be unique")
        return self


class UpdateSelectionAction(BaseModel):
    model_config = ConfigDict(extra="forbid")
    phase: Literal["update_confirmed"]
    selected_numbers: list[int] = Field(min_length=1)

    @model_validator(mode="after")
    def unique_numbers(self):
        if any(number < 1 for number in self.selected_numbers):
            raise ValueError("selected_numbers must be positive")
        if len(self.selected_numbers) != len(set(self.selected_numbers)):
            raise ValueError("selected_numbers must be unique")
        return self


class ModelDecision(BaseModel):
    """Internal envelope; IDs and history are never generated by the LLM."""

    model_config = ConfigDict(extra="forbid")
    status: Literal["ready", "needs_clarification", "unsupported"]
    intent: Literal["create_event", "list_events", "search_events", "on_delete", "on_update", "chat"] | None
    message: str | None
    action: (
        CreateEventAction
        | ListEventsAction
        | SearchEventsAction
        | DeleteFindCandidatesAction
        | DeleteSelectionAction
        | UpdateFindCandidatesAction
        | UpdateSelectionAction
        | None
    )
    draft: CreateEventDraft | ListEventsDraft | SearchEventsDraft | DeleteSearchDraft | UpdateSearchDraft | None
    topic_changed: StrictBool

    @model_validator(mode="after")
    def consistent(self):
        if self.status == "unsupported":
            if any(
                value is not None for value in (self.intent, self.message, self.action, self.draft)
            ):
                raise ValueError("Unsupported decisions must have null intent/message/action/draft")
        elif self.intent is None:
            raise ValueError("Supported decisions must specify intent")
        elif self.intent == "chat":
            if self.status != "ready" or not self.message or not self.message.strip() or self.action is not None or self.draft is not None:
                raise ValueError("Chat requires a message, null action and null draft")
        elif self.status == "ready":
            if (
                not self.message
                or not self.message.strip()
                or self.draft is not None
                or self.action is None
            ):
                raise ValueError("Ready requires nonblank message/action and null draft")
        elif (
            not self.message
            or not self.message.strip()
            or self.action is not None
            or self.draft is None
        ):
            raise ValueError("Clarification requires question/draft and null action")
        if self.status == "ready" and self.intent == "on_delete":
            if not isinstance(self.action, (DeleteFindCandidatesAction, DeleteSelectionAction)):
                raise ValueError("on_delete requires a delete phase action")
        elif self.status == "ready" and isinstance(
            self.action, (DeleteFindCandidatesAction, DeleteSelectionAction)
        ):
            raise ValueError("Delete action requires on_delete intent")
        if self.status == "ready" and self.intent == "on_update":
            if not isinstance(self.action, (UpdateFindCandidatesAction, UpdateSelectionAction)):
                raise ValueError("on_update requires an update phase action")
        elif self.status == "ready" and isinstance(
            self.action, (UpdateFindCandidatesAction, UpdateSelectionAction)
        ):
            raise ValueError("Update action requires on_update intent")
        return self
